-- 设备主机名（操作系统那层）随版本一起上报。
--
-- 为什么需要它：后台「节点管理」要区分「同一台机器上的多个智能体节点」，而
-- 机器主节点的昵称是**人起的名字**（可以叫「小久」），有时被改成了与主机无关的
-- 称呼，甚至为空。主机名是系统事实，两者都给出来，页面才能既认得出人、又对得上
-- 机器。
--
-- 为什么放在这张表而不是新建一张：这张表本来就是「一台机器一行」，版本、平台、
-- 升级进度都在这里；主机名与它们同一个生命周期（同一次 10 秒轮询上报），拆表只会
-- 多一次 join 和一次不一致的机会。
--
-- 空串 = 设备还没上报（1.3.4 之前的版本不上报）。写入端用
-- `NULLIF(EXCLUDED...,'')` 兜底，所以老设备的心跳不会把已有值擦掉。
ALTER TABLE rongcloud_node_upgrade
    ADD COLUMN IF NOT EXISTS reported_hostname text NOT NULL DEFAULT '';
